package com.tradeguide.domain.strategy;

/**
 * 검토용 매매 계획 미리보기 한 종목이 가질 수 있는 구체적 행동 초안의 종류다. 어떤 값도
 * 증권사 주문 전송이나 확정된 체결을 뜻하지 않으며, 사용자가 직접 검토하고 확인해야
 * 하는 초안이다.
 */
public enum PlannedTradeActionType {

    /**
     * 사용자 설정 손절가에 도달하면 보유 수량 전체를 청산하는 것을 검토하는 행동.
     * 손절가가 설정된 보유 종목이면 현재 가격과 무관하게 항상 제시한다.
     */
    PROTECTIVE_EXIT_REVIEW,

    /**
     * 위험 기준 대비 이익 구간에 있는 보유 종목의 부분 이익 실현을 검토하는 행동. 검증·
     * 백테스트된 목표가 규칙이 아직 등록되지 않아 현재는 목표가와 수량을 제시하지 않는
     * 비실행 항목으로만 존재한다.
     */
    PARTIAL_PROFIT_REVIEW,

    /**
     * 이미 보유 중인 종목에 대해 Track A가 신규 매수 신호를 낸 경우, 매도가 아니라 포지션
     * 추가를 검토하는 행동. 수량은 남은 종목당 노출 한도와 주문당 최대 손실 한도로
     * 제한한다.
     */
    POSSIBLE_ADD_REVIEW
}
