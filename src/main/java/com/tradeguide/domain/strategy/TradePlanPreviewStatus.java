package com.tradeguide.domain.strategy;

/**
 * 검토용 매매 계획 미리보기 한 종목의 상태다. 어떤 상태도 증권사 주문 전송이나 확정된
 * 수량을 뜻하지 않으며, 사용자가 직접 검토하고 확인해야 하는 초안이다.
 */
public enum TradePlanPreviewStatus {

    /** 위험 한도와 손절가를 기준으로 계산한 검토용 매수 후보 계획. */
    BUY,

    /** 전략 기준 가격이 손절가에 도달해 보유 수량 전체의 손절 검토가 필요한 상태. */
    STOP_LOSS_EXIT_REVIEW,

    /** 손절 발동 없이 하락 추세만으로 보유 수량 매도를 검토하는 상태. 수량은 임의 산출하지 않는다. */
    SELL_REVIEW,

    /** 상승 추세로 보유 수량을 유지하는 상태. 신규 매수나 매도 계획이 없다. */
    HOLD,

    /**
     * 이미 보유 중인 종목에 Track A 신규 매수 신호가 발생해 매도가 아니라 포지션 추가를
     * 검토하는 상태. 수량은 남은 종목당 노출 한도와 주문당 최대 손실 한도로 제한한다.
     */
    POSSIBLE_ADD_REVIEW,

    /** 신규 진입 조건을 충족하지 못해 관찰하는 상태. 매수 계획이 없다. */
    WATCH,

    /** 손절가나 위험 한도 정책이 없어 수치화된 계획을 계산할 수 없는 상태. */
    NOT_READY
}
