package com.tradeguide.domain.broker;

/**
 * 스테이징된 주문 한 건의 분류다. 서로 배타적이며, 실행의 사유별 건수는 이 분류를 센 값이다.
 *
 * <p>어떤 값이든 매매 원장 반영을 뜻하지 않는다. {@link #STAGED}조차 "반영 후보"라는 뜻이며,
 * 실제 반영 여부는 사용자 승인이 있는 별도 단계에서 결정한다.
 */
public enum BrokerOrderStagingStatus {
    /** 반영 후보다. 종료 상태이고 체결분·평균가·최종 체결 시각이 모두 있다. */
    STAGED,
    /** 체결분이 없다. 거래가 아니므로 정상 제외다. */
    SKIPPED_NOT_FILLED,
    /**
     * 부분 체결이라 더 체결될 수 있다. 제공자가 종료 그룹으로 돌려줬더라도 종료로 단정하지 않는다.
     * 나중에 같은 구간을 다시 조회하면 종료 상태로 들어온다.
     */
    PENDING_SETTLEMENT,
    /** 취소·정정 요청이 거부되어 생긴 제어 기록이다. 거래가 아니다. */
    SKIPPED_CONTROL_RECORD,
    /** 체결분은 있으나 반영에 필요한 값이 없거나 해석할 수 없는 상태다. 버리지 않고 남긴다. */
    SKIPPED_UNSUPPORTED,
    /** 이 주문은 이미 매매 원장에 반영돼 있다. 재조회가 정상 동작한 결과다. */
    ALREADY_IMPORTED,
    /** 사용자가 손으로 적은 매매와 같은 거래로 보인다. 자동으로 고르지 않고 사용자 판단으로 넘긴다. */
    MANUAL_OVERLAP_SUSPECTED,
    /**
     * 주문 식별자는 다른데 내용 지문이 이미 아는 주문과 같다.
     * 제공자가 재조회마다 다른 식별자를 주고 있을 가능성이 있어 자동 반영을 막는다.
     */
    DUPLICATE_SUSPECTED
}
