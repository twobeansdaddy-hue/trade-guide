package com.tradeguide.domain.broker;

/**
 * 스테이징 대상을 원장에 넣었다고 가정하고 재구성한 보유 수량을, 증권사가 보고한 최신 보유
 * 스냅샷과 맞춰 본 결과다. 이 대조는 어떤 행도 바꾸지 않는다.
 *
 * <p>차이가 있다는 것은 이력이 앞에서 잘렸거나, 앱에서 낸 주문이 응답에 빠졌거나,
 * 어떤 주문이 두 번 계상됐다는 신호다. 셋 다 조용히 틀리는 방식으로 나타나므로
 * 이 대조가 유일한 관측 수단이다.
 */
public enum BrokerOrderReconciliationStatus {
    /** 종목별 수량이 모두 일치한다. */
    MATCHED,
    /** 하나 이상의 종목에서 수량이 다르다. */
    MISMATCHED,
    /** 저장된 증권사 보유 종목 스냅샷이 없어 대조할 기준이 없다. */
    NOT_AVAILABLE,
    /**
     * 재구성 중 보유 수량보다 많은 매도가 나와 재생이 성립하지 않았다.
     * 이력 앞부분이 잘렸을 때 나타나며, 차이를 메우는 합성 매수를 만들지 않고 그대로 보고한다.
     */
    REPLAY_FAILED
}
