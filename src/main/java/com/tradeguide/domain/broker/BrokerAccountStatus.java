package com.tradeguide.domain.broker;

/**
 * 증권사 계좌 행의 생애주기 상태다.
 *
 * <p>계좌 행은 과거 스냅샷과 개시 잔고 승인 이력이 참조하는 식별자이므로,
 * 재검증 결과에 따라 지우지 않고 상태만 바꾼다.
 */
public enum BrokerAccountStatus {

    /** 가장 최근 검증에서 증권사가 반환한 계좌다. 후보 목록에 노출되고 포트폴리오에 연결할 수 있다. */
    ACTIVE,

    /**
     * 가장 최근 검증에서 증권사가 반환하지 않은 계좌다. 후보 목록에서 숨기고 새로 연결할 수 없지만,
     * 과거 스냅샷과 승인 이력이 계속 참조할 수 있도록 행 자체는 남긴다.
     */
    DETACHED
}
