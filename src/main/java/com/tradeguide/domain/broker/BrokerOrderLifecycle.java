package com.tradeguide.domain.broker;

/**
 * 제공자 원본 상태 코드를 해석해 얻은 중립 라이프사이클 판정이다.
 * 서비스 계층은 제공자 상태 문자열을 직접 해석하지 않고 이 값으로만 분기한다.
 *
 * <p>이 판정은 "주문이 어떤 상태인가"만 말한다. 체결가·체결 시각이 함께 왔는지 같은
 * 데이터 완전성 판단은 {@link BrokerOrderRecord}의 값으로 별도 확인한다.
 */
public enum BrokerOrderLifecycle {
    /** 진행 중이며 체결분이 없다. 원장 후보가 아니다. */
    NOT_FILLED,
    /**
     * 부분 체결 상태다. 더 체결될 수 있으므로 원장에 넣지 않고 보류한다.
     * 제공자가 이 주문을 종료 그룹으로 돌려주더라도 종료로 단정하지 않는다.
     */
    PARTIALLY_FILLED_OPEN,
    /** 종료 상태이고 체결분이 있다. 원장 반영 후보다. */
    TERMINAL_WITH_FILL,
    /** 종료 상태이고 체결분이 없다. 거래가 아니므로 원장 후보가 아니다. */
    TERMINAL_WITHOUT_FILL,
    /**
     * 취소·정정 요청이 거부되어 생긴 제어 기록이다.
     * 거래가 아니며, 원주문의 체결 집계를 복제할 수 있으므로 원장에 넣지 않는다.
     */
    CONTROL_RECORD,
    /** 제공자가 이 클라이언트가 모르는 상태 값을 보냈다. 파싱을 실패시키지 않고 판정만 보류한다. */
    UNKNOWN
}
