package com.tradeguide.domain.broker;

/**
 * 정합성 점검에서 종목 한 줄의 차이를 설명하는 사유 후보다. 판정이 아니라 후보이며,
 * {@link #UNEXPLAINED_DIFFERENCE}를 뺀 나머지는 저장된 데이터만으로 계산한 정황이다.
 * 화면은 이 값으로 사용자가 다음에 확인할 행동을 제시하고, 최종 판단은 사용자가 내린다.
 *
 * <p>이 점검은 증권사를 호출하지 않으므로, 여기서 만드는 사유도 이미 저장된 주문 이력 실행·
 * 개시 잔고 승인 이력·제공자 카탈로그만으로 계산한다. 한 줄에 여러 사유가 함께 붙을 수 있다.
 */
public enum BrokerReconciliationReasonCode {

    /**
     * 계좌의 최근 주문 이력 실행에 이 종목의 반영 후보 주문이 있고, 아직 원장에 반영되지
     * 않았다. 사용자가 그 실행을 승인하면 차이가 해소될 수 있다.
     */
    UNAPPROVED_RUN_EXISTS,

    /**
     * 계좌의 최근 주문 이력 실행에 이 종목의 주문이 있지만, 활성 개시 잔고 기준 시각보다
     * 먼저 체결됐다. 그 시점 보유분은 이미 개시 잔고에 포함돼 있어야 하는 이력이므로
     * 승인 대상에서 제외된다.
     */
    BASELINE_EXCLUDED_HISTORY,

    /** 이 종목에 아직 체결이 끝나지 않은 부분 체결 주문이 있다. 더 체결되면 값이 달라진다. */
    UNSETTLED_OR_PARTIAL_FILL,

    /**
     * 이 계좌에 성공한 주문 이력 실행이 없거나, 가장 최근 실행의 조회 구간이 이번 스냅샷
     * 기준 시각보다 앞서 끝난다. 조회하지 않은 기간에 이 종목의 거래가 있었을 수 있다.
     */
    OUT_OF_PERIOD_HISTORY,

    /**
     * 이 종목의 시장이 현재 매매 원장에 반영할 수 있는 시장이 아니다. 원장이 통화 개념을
     * 아직 표현하지 못해 생기는 구조적 차이이며, 사용자 조작으로 해소되지 않는다.
     */
    LEDGER_MARKET_UNSUPPORTED,

    /** 위 사유 중 어느 것도 이 차이를 설명하지 못한다. 사람이 직접 판단해야 한다. */
    UNEXPLAINED_DIFFERENCE
}
